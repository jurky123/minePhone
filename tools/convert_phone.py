"""Convert supplied phone geometry and textures, without executing archive scripts."""
from pathlib import Path
import json, shutil

ROOT = Path(__file__).resolve().parents[1]
source = json.loads((ROOT/'tools/model-assets/phone_geometry_source.json').read_text(encoding='utf-8'))
parts = source['objects']
colors = ['case','case_light','edge','dark','black','metal','cyan','cyan_dark','white','amber','rubber','screw','screen_dark','blue','teal','mint']
assets = ROOT/'src/main/resources/assets/browserlink'
scale = 14/60
def point(v):
    x,y,z = v
    return [8+x*scale, 1+z*scale, 8-y*scale]

elements=[]; bounds=[]
for p in parts:
    c=point(p['center_grid']); dx,dy,dz=p['size_grid']; size=[dx*scale,dz*scale,dy*scale]
    lo=[v-s/2 for v,s in zip(c,size)]; hi=[v+s/2 for v,s in zip(c,size)]
    bounds.extend([lo,hi]); i=colors.index(p['palette']); u=(i%4)*4+2; v=(i//4)*4+2
    elements.append({'from':lo,'to':hi,'faces':{face:{'texture':'#body','uv':[u,v,u,v]} for face in ['north','south','east','west','up','down']}})
model={'ambientocclusion':False,'textures':{'body':'browserlink:item/phone_body_atlas','particle':'browserlink:item/phone_body_atlas'},'elements':elements}
(assets/'models/item/phone_body.json').write_text(json.dumps(model,indent=2),encoding='utf-8')
shutil.copy2(ROOT/'tools/model-assets/phone_body_atlas.png',assets/'textures/item/phone_body_atlas.png')
shutil.copy2(ROOT/'tools/model-assets/phone_screen.png',assets/'textures/phone_idle.png')
# Original screen is x=-12.5..12.5, z=5..55, y=-2.06. Transform once for both renderers.
a=point([-12.5,-2.06,5]); b=point([12.5,-2.06,55])
screen=[a[0]/16,a[1]/16,b[0]/16,b[1]/16,a[2]/16]
box=[min(v[i] for v in bounds)/16 for i in range(3)]+[max(v[i] for v in bounds)/16 for i in range(3)]
java='package dev.browserlink;\n\n/** Generated by tools/convert_phone.py from the supplied 84 body parts and screen. */\npublic final class PhoneGeometry {\n'
java+='    public static final float[] SCREEN={'+', '.join(f'{v:.9f}f' for v in screen)+'};\n'
java+='    public static final float[] BOUNDS={'+', '.join(f'{v:.9f}f' for v in box)+'};\n'
java+='    private PhoneGeometry() {}\n}\n'
(ROOT/'src/main/java/dev/browserlink/PhoneGeometry.java').write_text(java,encoding='utf-8')
assert len(parts)==84
assert all(-16<=v<=32 for p in bounds for v in p)
print('Phone:',len(parts),'body parts + screen; screen',screen)
