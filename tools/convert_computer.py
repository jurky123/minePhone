"""Convert user-authored cuboids, without executing scripts in the asset archive."""
from pathlib import Path
import json,shutil
ROOT=Path(__file__).resolve().parents[1]
parts=json.loads((ROOT/'tools/model-assets/geometry_source.json').read_text())
colors=['case','case_light','edge','dark','black','metal','cyan','cyan_dark','white','amber','rubber','screw','screen_dark','blue','teal','mint']
offsets={'monitor':[-10,1,0],'tower':[14,0,0]}
boxes=[]
for p in parts:
 c=[a+b for a,b in zip(p['center_voxels'],offsets[p['group']])]
 lo=[a-b/2 for a,b in zip(c,p['size_voxels'])];hi=[a+b/2 for a,b in zip(c,p['size_voxels'])]
 boxes.append((p,lo,hi))
low=[min(b[1][i] for b in boxes) for i in range(3)];high=[max(b[2][i] for b in boxes) for i in range(3)]
scale=24/(high[0]-low[0]);cx=(low[0]+high[0])/2;cy=(low[1]+high[1])/2
els=[];collisions=[]
for p,lo,hi in boxes:
 a=[8+(lo[0]-cx)*scale,lo[2]*scale,8-(hi[1]-cy)*scale]
 b=[8+(hi[0]-cx)*scale,hi[2]*scale,8-(lo[1]-cy)*scale]
 idx=colors.index(p['palette']);u=((idx%8)*32+16)/16;v=((idx//8)*32+16)/16
 faces={f:{'texture':'#atlas','uv':[u,v,u,v]} for f in ['north','south','east','west','up','down']}
 if p['screen']:
  faces['south']['uv']=[.5/16,96.5/16,159.5/16,191.5/16]
  screen=[a[0]/16,a[1]/16,b[0]/16,b[1]/16,b[2]/16+.00015]
 els.append({'name':p['name'],'from':a,'to':b,'faces':faces})
 if p['name'].startswith(('M01 ','M02 ','M04 ','M08 ','M09 ','T01 ','T02 ','T03 ')):collisions.append(a+b)
assets=ROOT/'src/main/resources/assets/browserlink'
(assets/'models/block/computer.json').write_text(json.dumps({'textures':{'atlas':'browserlink:block/computer_atlas','particle':'browserlink:block/computer_atlas'},'elements':els},indent=2))
(assets/'textures/block').mkdir(exist_ok=True)
shutil.copy2(ROOT/'tools/model-assets/voxel_computer_atlas.png',assets/'textures/block/computer_atlas.png')
(assets/'models/item/computer.json').write_text(json.dumps({'parent':'browserlink:block/computer','display':{'gui':{'rotation':[25,25,0],'translation':[0,2,0],'scale':[.625,.625,.625]},'ground':{'translation':[0,3,0],'scale':[.5,.5,.5]},'fixed':{'translation':[0,3,0],'scale':[.625,.625,.625]}}},indent=2))
nums=', '.join(f'{n:.8f}f' for n in screen)
boxlines=',\n        '.join('{'+', '.join(f'{v:.8f}' for v in b)+'}' for b in collisions)
source='''package dev.browserlink;

import net.minecraft.core.Direction;
import net.minecraft.world.phys.shapes.Shapes;
import net.minecraft.world.phys.shapes.VoxelShape;

/** Generated by tools/convert_computer.py from the user-supplied model. */
public final class ComputerGeometry {
    public static final float[] SCREEN = new float[]{SCREEN_NUMS};
    private static final double[][] BOXES = {
        BOX_LINES
    };
    private static final VoxelShape[] SHAPES = new VoxelShape[4];
    static {
        for (Direction d : Direction.Plane.HORIZONTAL) {
            VoxelShape result = Shapes.empty();
            for (double[] b : BOXES) {
                double x1=b[0],z1=b[2],x2=b[3],z2=b[5];
                double[] r = switch(d) {
                    case WEST -> new double[]{z1,16-x2,z2,16-x1};
                    case NORTH -> new double[]{16-x2,16-z2,16-x1,16-z1};
                    case EAST -> new double[]{16-z2,x1,16-z1,x2};
                    default -> new double[]{x1,z1,x2,z2};
                };
                result=Shapes.or(result,Shapes.box(r[0]/16,b[1]/16,r[1]/16,r[2]/16,b[4]/16,r[3]/16));
            }
            SHAPES[d.get2DDataValue()]=result.optimize();
        }
    }
    public static VoxelShape shape(Direction direction) { return SHAPES[direction.get2DDataValue()]; }
    private ComputerGeometry() {}
}
'''.replace('SCREEN_NUMS',nums).replace('BOX_LINES',boxlines)
(ROOT/'src/main/java/dev/browserlink/ComputerGeometry.java').write_text(source)
assert len(els)==121
assert all(-16<=v<=32 for e in els for v in e['from']+e['to'])
print('Converted',len(els),'cuboids; screen=',screen,'scale=',scale)
